CREATE TABLE IF NOT EXISTS admin (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    creationdate timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updationdate varchar(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS category (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoryname varchar(255),
    categorydescription text,
    creationdate timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updationdate varchar(255)
);

CREATE TABLE IF NOT EXISTS orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid integer,
    productid varchar(255),
    quantity integer,
    orderdate timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paymentmethod varchar(50),
    orderstatus varchar(55)
);

CREATE TABLE IF NOT EXISTS ordertrackhistory (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orderid integer,
    status varchar(255),
    remark text,
    postingdate timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS productreviews (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    productid integer,
    quality integer,
    price integer,
    value integer,
    name varchar(255),
    summary varchar(255),
    review text,
    reviewdate timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS products (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category integer NOT NULL,
    subcategory integer,
    productname varchar(255),
    productcompany varchar(255),
    productprice integer,
    productpricebeforediscount integer,
    productdescription text,
    productimage1 varchar(255),
    productimage2 varchar(255),
    productimage3 varchar(255),
    shippingcharge integer,
    productavailability varchar(255),
    postingdate timestamptz DEFAULT CURRENT_TIMESTAMP,
    updationdate varchar(255)
);

CREATE TABLE IF NOT EXISTS subcategory (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoryid integer,
    subcategory varchar(255),
    creationdate timestamptz DEFAULT CURRENT_TIMESTAMP,
    updationdate varchar(255)
);

CREATE TABLE IF NOT EXISTS userlog (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    useremail varchar(255),
    userip inet,
    logintime timestamptz DEFAULT CURRENT_TIMESTAMP,
    logout varchar(255),
    status integer
);

CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255),
    email varchar(255),
    contactno bigint,
    password varchar(255),
    shippingaddress text,
    shippingstate varchar(255),
    shippingcity varchar(255),
    shippingpincode integer,
    billingaddress text,
    billingstate varchar(255),
    billingcity varchar(255),
    billingpincode integer,
    regdate timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updationdate varchar(255)
);

CREATE TABLE IF NOT EXISTS wishlist (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid integer,
    productid integer,
    postingdate timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS payments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL,
    status varchar(50),
    paypal_payment_id varchar(255)
);

CREATE INDEX IF NOT EXISTS idx_products_category ON products (category);
CREATE INDEX IF NOT EXISTS idx_products_subcategory ON products (subcategory);
CREATE INDEX IF NOT EXISTS idx_orders_userid ON orders (userid);
CREATE INDEX IF NOT EXISTS idx_wishlist_userid ON wishlist (userid);
